/**
 * Booking and calendars · Retention and advocacy · Marketing and what is already in market.
 * The three Diagnosis chapters that follow a client from the moment a conversation is booked,
 * through the years after settlement, out to the surfaces that already carry their claims.
 *
 * These three sit together because they share one failure: a date, a record or a permission
 * that was never captured, and so nothing downstream of it can fire. Booking decides whether a
 * conversation and its paperwork ever get a record at all. Retention decides whether the dates
 * that drive every post settlement touch exist as dates rather than as a memory. Marketing is
 * the catalogue of what is already published, gathered so it can be reviewed by the people whose
 * licence it sits under. Nothing here rules on a client's compliance position, and nothing here
 * describes what we would do about any of it.
 */
